import { expect, test } from "@playwright/test";
import { createServer } from "./fixtures/vite.js";

for (const width of [390, 1360]) test.describe(`${width}px`, () => {
  test.use({ viewport: { width, height: 844 }, isMobile: width < 760, hasTouch: width < 760 });
test(`Bot selection keeps task drafts and returns one level`, async ({ page }, info) => {
  await page.setViewportSize({ width, height: 844 });
  const server = await createServer({ server: { port: 0, host: "127.0.0.1" } }); await server.listen();
  try {
    await page.goto(server.resolvedUrls!.local[0] + "e2e/fixtures/schedule-picker.html");
    const dialog = page.getByRole("dialog"), trigger = dialog.getByRole("button", { name: "执行 Bot", exact: true });
    await expect(trigger).toHaveAccessibleDescription(/研究助手.*在线/);
    await trigger.click();
    await expect(dialog).toHaveAccessibleName("选择执行 Bot");
    await expect(page.locator("dialog[open]")).toHaveCount(1);
    await expect(dialog.locator("select:visible")).toHaveCount(0);
    await expect(dialog.locator(".schedule-bot-option")).toHaveCount(50);
    await expect(dialog.locator(".schedule-bot-option[aria-current=true]")).toContainText("研究助手");
    await expect(dialog.getByRole("searchbox")).not.toBeFocused();
    await expect(dialog.locator(".schedule-bot-option").first()).toHaveCSS("min-height", "60px");
    await page.screenshot({ path: info.outputPath(`schedule-picker-${width}.png`), animations: "disabled" });
    await page.emulateMedia({ reducedMotion: "reduce" });
    await expect(dialog.locator(".schedule-bot-picker")).toHaveCSS("animation-name", "none");
    await dialog.getByRole("searchbox").fill("工作助手 59");
    await expect(dialog.locator(".schedule-bot-option")).toHaveCount(1);
    await dialog.getByRole("searchbox").fill("查无此助手");
    await expect(dialog.getByRole("status")).toHaveText("没有匹配的 Bot");
    await dialog.getByRole("searchbox").fill("");
    await dialog.getByRole("button", { name: "显示更多 Bot", exact: true }).click();
    await expect(dialog.locator(".schedule-bot-option")).toHaveCount(64);
    await dialog.locator(".schedule-bot-options").evaluate(node => node.scrollTop = 1200);
    await expect(dialog.getByRole("button", { name: "返回定时任务", exact: true })).toBeInViewport();
    await expect(dialog.getByRole("searchbox")).toBeInViewport();
    await page.setViewportSize({ width, height: 430 });
    await expect(dialog.getByRole("button", { name: "返回定时任务", exact: true })).toBeInViewport();
    expect(await dialog.evaluate(node => node.scrollHeight <= node.clientHeight)).toBe(true);
    await page.setViewportSize({ width, height: 844 });
    // The native Android back event returns to the task page, not "My".
    await page.evaluate(() => window.dispatchEvent(new Event("tarocub-native-back", { cancelable: true })));
    await expect(dialog).toHaveAccessibleName("定时任务"); await expect(trigger).toBeFocused();
    await dialog.getByRole("button", { name: "新建定时任务", exact: true }).click();
    await dialog.getByLabel("任务名称", { exact: true }).fill("保留未发送的日报");
    await dialog.getByRole("textbox", { name: "任务内容", exact: true }).fill("保留两行内容\n第二行");
    await dialog.getByLabel("结果发送到").selectOption("result");
    await dialog.getByText("上下文设置", { exact: true }).click();
    await trigger.click(); await dialog.getByRole("button", { name: "返回定时任务", exact: true }).click();
    await expect(dialog.getByLabel("结果发送到")).toHaveValue("result");
    await expect(dialog.getByLabel("执行上下文", { exact: true })).toBeVisible();
    await trigger.click(); await dialog.locator(".schedule-bot-option[aria-current=true]").click();
    await expect(dialog.getByLabel("结果发送到")).toHaveValue("result");
    await trigger.click(); await dialog.getByRole("button", { name: "日历与邮件助手 在线", exact: true }).click();
    await expect(trigger).toContainText("日历与邮件助手");
    await expect(dialog.getByLabel("结果发送到")).toHaveValue("");
    await expect(dialog.getByLabel("任务名称", { exact: true })).toHaveValue("保留未发送的日报");
    await expect(dialog.getByRole("textbox", { name: "任务内容", exact: true })).toHaveValue("保留两行内容\n第二行");
    await trigger.click(); await page.keyboard.press("Escape");
    await expect(dialog).toHaveAccessibleName("新建定时任务"); await expect(trigger).toBeFocused();
    await trigger.click(); await dialog.getByRole("button", { name: "离线的写作助手 离线", exact: true }).click();
    await expect(trigger).toContainText("离线的写作助手");
    await expect(dialog.getByRole("button", { name: "创建定时任务", exact: true })).toBeDisabled();
    await trigger.click();
    await page.evaluate(() => (window as any).scheduleFixture.removeBot("beta"));
    await expect(dialog.getByRole("button", { name: "日历与邮件助手 在线", exact: true })).toHaveCount(0);
    await dialog.getByRole("searchbox").fill("工作助手 59");
    await dialog.locator(".schedule-bot-option").click();
    await trigger.click();
    await expect(dialog.locator(".schedule-bot-option").first()).toContainText("工作助手 59");
    await page.evaluate(() => (window as any).scheduleFixture.removeBot("bot_59"));
    await dialog.getByRole("button", { name: "返回定时任务", exact: true }).click();
    await expect(trigger).toContainText("所选 Bot 已不可用");
    await expect(dialog.getByRole("button", { name: "创建定时任务", exact: true })).toBeDisabled();
    await trigger.click();
    expect(await dialog.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true);
    await page.evaluate(() => document.documentElement.dataset.theme = "dark");
    await page.screenshot({ path: info.outputPath(`schedule-picker-dark-${width}.png`), animations: "disabled" });
    await page.evaluate(() => { document.documentElement.dataset.theme = "light"; document.documentElement.dataset.palette = "cli"; });
    await page.screenshot({ path: info.outputPath(`schedule-picker-cli-${width}.png`), animations: "disabled" });
    await page.evaluate(() => (window as any).scheduleFixture.keepFirst(2));
    await expect(dialog.locator(".schedule-bot-option")).toHaveCount(2);
    expect((await dialog.boundingBox())!.height).toBeLessThan(400);
  } finally { await page.close(); await server.close(); }
});
});
