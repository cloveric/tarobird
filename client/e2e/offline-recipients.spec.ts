import { preparePairing } from "./fixtures/pairing-invite.js";
import { test, expect } from "@playwright/test";
import { mkdtemp, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { HubServer } from "../../src/hub/server.js";
import { blocksText } from "../../src/client-protocol/index.js";
import { revealReplyBots, dismissReplyBots } from "./fixtures/desktop-actions.js";
import { selectConversation, waitForClientOnline } from "./fixtures/mobile.js";

for (const phone of [false, true]) test(`offline cold starts retain group recipients and deliver each queued message once (${phone ? "phone" : "desktop"})`, async ({ page }) => {
  const root = await mkdtemp(path.join(os.tmpdir(), "offline-recipients-"));
  let hub: HubServer | undefined = await HubServer.start({ stateDir: root, clientDir: path.resolve("dist") });
  const port = Number(new URL(hub.url).port);
  const errors: string[] = []; page.on("pageerror", error => errors.push(error.message));
  try {
    if (phone) await page.setViewportSize({ width: 390, height: 844 });
    await hub.store.db.run("INSERT INTO bots(id,name,secret_hash) VALUES('alpha','助手甲','fixture'),('beta','助手乙','fixture'),('outsider','非群成员','fixture')");
    const group = await hub.store.createConversation("owner", ["alpha", "beta"], "离线群聊", "group", { type: "group" });
    const topic = await hub.store.createConversation("owner", [], "独立话题", "topic", { parentId: group.id });
    await page.goto(hub.url);
    await preparePairing(page, hub); await page.getByRole("button", { name: "配对此设备", exact: true }).click();
    await hub.auth.approve(await page.getByLabel("配对码", { exact: true }).innerText(), "local-owner");
    await page.getByLabel("配对码", { exact: true }).waitFor({ state: "hidden" });
    await waitForClientOnline(page); await selectConversation(page, group.title);
    await revealReplyBots(page);
    await page.getByRole("checkbox", { name: "助手甲", exact: true }).check();
    await dismissReplyBots(page);
    await expect(page.getByLabel("草稿状态", { exact: true })).toHaveText("草稿已保存");
    await page.evaluate(() => navigator.serviceWorker.ready.then(() => undefined));
    await expect.poll(() => page.evaluate(() => !!navigator.serviceWorker.controller)).toBe(true);
    await hub.close(); hub = undefined;
    await page.reload({ waitUntil: "domcontentloaded" });
    await selectConversation(page, group.title);
    await expect(page.locator(".offline-banner").filter({ visible: true })).toBeVisible();
    await revealReplyBots(page);
    await expect(page.getByRole("checkbox", { name: "助手甲", exact: true })).toHaveAttribute("aria-checked", "true");
    await expect(page.getByRole("checkbox", { name: "助手乙", exact: true })).toBeVisible();
    await expect(page.getByRole("checkbox", { name: "非群成员", exact: true })).toHaveCount(0);
    await page.getByRole("checkbox", { name: "助手甲", exact: true }).click();
    await dismissReplyBots(page);
    const input = page.getByRole("textbox", { name: "消息", exact: true });
    // Modern mentions-mode groups allow an unaddressed note. This journey
    // verifies explicit recipients and offline delivery, not the old guard.
    await expect(page.locator(".queued-message")).toHaveCount(0);
    await revealReplyBots(page);
    await page.getByRole("checkbox", { name: "助手乙", exact: true }).click();
    await dismissReplyBots(page);
    await input.fill("群聊保留给乙的草稿");
    await expect(page.getByLabel("草稿状态", { exact: true })).toHaveText("草稿已保存");
    await selectConversation(page, topic.title, phone ? group.title : undefined);
    await revealReplyBots(page);
    await page.getByRole("checkbox", { name: "助手甲", exact: true }).check();
    await dismissReplyBots(page);
    await input.fill("话题保留给甲的草稿");
    await expect(page.getByLabel("草稿状态", { exact: true })).toHaveText("草稿已保存");
    await page.reload({ waitUntil: "domcontentloaded" });
    await selectConversation(page, group.title);
    await expect(input).toHaveValue("群聊保留给乙的草稿");
    await revealReplyBots(page);
    await expect(page.getByRole("checkbox", { name: "助手甲", exact: true })).toHaveAttribute("aria-checked", "false");
    await expect(page.getByRole("checkbox", { name: "助手乙", exact: true })).toHaveAttribute("aria-checked", "true");
    await dismissReplyBots(page);
    await input.fill("@");
    await expect(page.locator(".command-menu").getByRole("button", { name: "助手乙", exact: true })).toBeVisible();
    await expect(page.locator(".command-menu").getByRole("button", { name: /非群成员/ })).toHaveCount(0);
    await page.locator(".command-menu").getByRole("button", { name: "助手乙", exact: true }).click();
    await expect(input).toHaveValue("");
    await revealReplyBots(page);
    await expect(page.getByRole("checkbox", { name: "助手乙", exact: true })).toHaveAttribute("aria-checked", "true");
    await dismissReplyBots(page);
    const texts = ["离线顺序一", "离线顺序二", "离线顺序三"];
    for (let index = 0; index < texts.length; index++) {
      await input.fill(texts[index]!);
      await page.getByRole("button", { name: "发送消息", exact: true }).click();
      await expect(input).toHaveValue("");
      await expect(page.locator(".queued-message")).toHaveCount(index + 1);
    }
    await page.reload({ waitUntil: "domcontentloaded" });
    await selectConversation(page, group.title);
    await expect(page.locator(".queued-message")).toHaveCount(3);
    await expect(page.locator(".offline-banner").filter({ visible: true })).toContainText("3 条消息将在重连后发送。");
    hub = await HubServer.start({ stateDir: root, port, clientDir: path.resolve("dist") });
    await waitForClientOnline(page);
    await expect(page.locator(".queued-message")).toHaveCount(0);
    const sent = (await hub.store.snapshot("owner", group.id)).messages.filter(message => message.authorType === "user");
    expect(sent.map(message => blocksText(message.blocks))).toEqual(texts);
    expect(sent.map(message => message.mentions)).toEqual([["beta"], ["beta"], ["beta"]]);
    expect(new Set(sent.map(message => message.clientMsgId)).size).toBe(3);
    await page.reload(); await waitForClientOnline(page);
    await selectConversation(page, topic.title, phone ? group.title : undefined);
    await expect(input).toHaveValue("话题保留给甲的草稿");
    await revealReplyBots(page);
    await expect(page.getByRole("checkbox", { name: "助手甲", exact: true })).toHaveAttribute("aria-checked", "true");
    expect((await hub.store.snapshot("owner", topic.id)).messages).toHaveLength(0);
    expect((await hub.store.snapshot("owner", group.id)).messages.filter(message => message.authorType === "user")).toHaveLength(3);
    expect(errors).toEqual([]);
  } finally { await page.close(); if (hub) await hub.close(); await rm(root, { recursive: true, force: true }); }
});
