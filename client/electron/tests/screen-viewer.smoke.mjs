import { build } from 'esbuild';
import { spawn } from 'node:child_process';
import { copyFile, mkdir, readFile, realpath } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { isolatedRoot } from '../isolation.mjs';
const [binary, output, quality = "balanced"] = process.argv.slice(2);
if (!["balanced", "sharp"].includes(quality)) throw new Error("invalid_smoke_quality");
if (!binary || !output) throw new Error('explicit isolated Electron binary and output required');
if (!(await realpath(binary)).split(path.sep).some(p => p.endsWith('.noindex'))) throw new Error('physical_noindex_binary_required');
const root = await isolatedRoot(output), source = path.join(path.dirname(fileURLToPath(import.meta.url)), 'screen-viewer');
await mkdir(path.join(root, 'profile'), { recursive: true });
await build({ entryPoints: [path.join(source, 'main.mjs')], outfile: path.join(root, 'main.cjs'), bundle: true, platform: 'node', format: 'cjs', external: ['electron'], define: { 'import.meta.dirname': JSON.stringify(root) } });
await build({ entryPoints: [path.join(source, 'renderer.ts')], outfile: path.join(root, 'renderer.js'), bundle: true, platform: 'browser', format: 'iife' });
await copyFile(path.join(source, 'preload.cjs'), path.join(root, 'preload.cjs'));
const env = { ...process.env, TAROBOT_SCREEN_SMOKE_QUALITY: quality }; delete env.ELECTRON_RUN_AS_NODE;
const child = spawn(binary, [path.join(root, 'main.cjs'), root], { env, stdio: ['ignore', 'pipe', 'pipe'] });
let log = ''; for (const stream of [child.stdout, child.stderr]) stream.on('data', data => { log = (log + data).slice(-16000); });
const watchdog = setTimeout(() => child.kill('SIGKILL'), 25000);
const code = await new Promise(resolve => child.once('exit', resolve)); clearTimeout(watchdog);
if (code !== 0) throw new Error(`screen smoke exit ${code}\n${log}`);
const result = JSON.parse(await readFile(path.join(root, 'verification.json'), 'utf8'));
assert.equal(result.passed, true); assert.ok(result.decoded >= 40); assert.ok(result.mainHeartbeatTicks >= 50); assert.ok(result.mainHeartbeatMaxMs < 2000);
console.log(JSON.stringify(result, null, 2));
